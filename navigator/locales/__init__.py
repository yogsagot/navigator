"""Navigator's translations: one ``<code>.toml`` per language, read by
:mod:`navkit.i18n` (see that module for the format)."""


def strings():
    """Tables of captions kept English and passed to ``tr()`` where shown.

    Read rather than marked: the palette's is regenerated by ``palconv.py
    --names``, and the key tables' titles head ``keybindings.ini`` sections.
    ``python -m navml extract`` asks for them, as ``(key, where)`` pairs.
    """
    from navigator.lib.config import keybindings
    from navigator.lib.appearance import palette
    where = "navigator/lib/appearance/palette.py"
    for _, _, group, item in palette.ENTRIES:
        yield group, where
        yield item, where
    yield palette.NAVIGATOR_GROUP, where
    for item in palette.DERIVED_ITEMS.values():
        yield item, where
    for _, title, _ in keybindings.TABLES:
        yield title, "navigator/lib/config/keybindings.py"
    from navigator.lib.drives.base import DESCRIBED
    for what in DESCRIBED:
        yield what, "navigator/lib/drives/base.py"
    # Every setting's doc: a setup page shows it as the tooltip of the
    # control that sets it (``Section.tooltip``/``tooltips``).  All of them
    # rather than the ones a page names today, so a page that starts showing
    # one finds it translated.
    from navigator import settings
    for section in settings.Section.__subclasses__():
        for field in section.fields():
            yield field.doc, "navigator/settings.py"
