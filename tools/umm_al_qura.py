#!/usr/bin/env python3
"""Write Saudi Arabia's Umm al-Qura calendar, ``navml/ummalqura_data.py``.

    ./venv/bin/python tools/umm_al_qura.py           # download and write it
    ./venv/bin/python tools/umm_al_qura.py --check   # exit 1 when it is inconsistent

The Umm al-Qura calendar is Saudi Arabia's official Hijri calendar: a month
begins by a computed rule (the moon set after the sun at Mecca on the 29th,
the conjunction before sunset, as it has been since 1423 AH), published as a
table rather than a formula.  Robert Harry van Gent (Utrecht University)
keeps it as the first day of every month from 1 Muharram 1356 (14 March 1937)
to the end of 1500 (16 November 2077): ``ummalqura_dat`` in his converter's
``islamcalendar_dat.js``, each a *Modified Chronological Julian Day Number*,
the day's Julian Day Number less 2,400,000, the first that of 1 Muharram 1356
and the last the day after the table's last month.  Here they are those
days' ``date.toordinal()``.

Its years before 1392 AH come from a conversion table the King Fahd
University of Petroleum & Minerals published in the early 1990s, which no one
rule explains, and Sha'ban 1364 (August 1945) has 28 days in it -- not a lunar
month, most likely the printed table's slip, but what the official tables say,
so it is kept (:data:`KNOWN`).

``--check`` needs no network: it says whether every month is 29 or 30 days,
but for :data:`KNOWN`, and every year whole.
"""

from __future__ import annotations

import argparse
import datetime
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODULE = ROOT / "navml" / "ummalqura_data.py"

URL = "https://webspace.science.uu.nl/~gent0113/islam/addfiles/islamcalendar_dat.js"
#: The table's first month, as van Gent's converter counts it (its lunation 16261).
FIRST_YEAR = 1356
#: A Julian Day Number less this is van Gent's day; a ``date``'s ordinal is the
#: Julian Day Number less 1,721,425.
MCJDN, ORDINAL = 2_400_000, 1_721_425
#: Months of another length that the table has, by (year, month).
KNOWN = {(1364, 8): 28}

HEADER = '''# navml: generated by tools/umm_al_qura.py from R. H. van Gent's tabulation of
# Saudi Arabia's Umm al-Qura calendar; do not edit.
"""The Umm al-Qura calendar's months, 1 Muharram {first} to the end of {last} AH.

``MONTH_STARTS[n]`` is the first day (``datetime.date.toordinal()``) of month
``n % 12 + 1`` of year ``FIRST_YEAR + n // 12``; the last entry is the day
after the table's last month.
"""

FIRST_YEAR = {first}

MONTH_STARTS: tuple[int, ...] = (
'''


def table(source: str) -> list[int]:
    """``ummalqura_dat``'s days, as ordinals."""
    match = re.search(r"ummalqura_dat\s*=\s*new Array\(([^)]*)\)", source)
    if match is None:
        raise ValueError("no ummalqura_dat in the file")
    return [int(value) + MCJDN - ORDINAL for value in re.findall(r"\d+", match[1])]


def module_text(starts: list[int]) -> str:
    years = (len(starts) - 1) // 12
    rows = []
    for year in range(years):
        months = starts[12 * year:12 * year + 12]
        rows.append("    " + ", ".join(str(day) for day in months) + f",  # {FIRST_YEAR + year}\n")
    rows.append(f"    {starts[-1]},  # the day after\n")
    head = HEADER.format(first=FIRST_YEAR, last=FIRST_YEAR + years - 1)
    return head + "".join(rows) + ")\n"


def check() -> int:
    namespace: dict = {}
    exec(MODULE.read_text(encoding="utf-8"), namespace)
    starts = namespace["MONTH_STARTS"]
    problems = []
    if (len(starts) - 1) % 12:
        problems.append(f"{len(starts) - 1} months is not a number of years")
    for index, (start, after) in enumerate(zip(starts, starts[1:])):
        year, month = namespace["FIRST_YEAR"] + index // 12, index % 12 + 1
        if after - start not in (29, 30) and KNOWN.get((year, month)) != after - start:
            problems.append(f"{year}/{month}: {after - start} days")
    for problem in problems:
        print(f"{MODULE}: {problem}", file=sys.stderr)
    return 1 if problems else 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when the module is inconsistent")
    args = parser.parse_args()
    if args.check:
        return check()
    with urllib.request.urlopen(URL, timeout=60) as response:
        starts = table(response.read().decode("utf-8", errors="replace"))
    MODULE.write_text(module_text(starts), encoding="utf-8")
    first = datetime.date.fromordinal(starts[0])
    print(f"wrote {MODULE}: 1 Muharram {FIRST_YEAR} is {first}, {(len(starts) - 1) // 12} years")
    return check()


if __name__ == "__main__":
    sys.exit(main())
