#!/usr/bin/env python3
"""Write the Chinese calendar's months, ``navml/chinese_data.py``.

    ./venv/bin/python tools/chinese_calendar.py                 # download and write it
    ./venv/bin/python tools/chinese_calendar.py --cache DIR     # keep the downloads in DIR
    ./venv/bin/python tools/chinese_calendar.py --check         # exit 1 when it is inconsistent

The Chinese calendar has no formula: a month begins on the day of the new
moon in Beijing's time, and which month is leap follows the solar terms, so
it comes from an ephemeris or from someone who ran one.  Here it is the Hong
Kong Observatory's *Gregorian-Lunar Calendar Conversion Table*, one text file
a year for 1901 to 2100 (``T2026e.txt``: each Gregorian day, and on the first
day of a lunar month ``6th Lunar Month`` (``month`` until 2010), a leap month repeating the number
of the month before it).  From those the months are counted: where each lunar
year begins and how long its months are.  The lunar years wholly inside them
are kept, 1901 (which begins on 19 February 1901) to 2099.

``--check`` needs no network: it says whether the module's years follow one
another without a gap, each with twelve months or thirteen, of 29 or 30 days.
"""

from __future__ import annotations

import argparse
import datetime
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODULE = ROOT / "navml" / "chinese_data.py"

URL = "https://www.hko.gov.hk/en/gts/time/calendar/text/files/T{year}e.txt"
FIRST_FILE, LAST_FILE = 1901, 2100

#: A day's line; until 2010 the files write ``Lunar month``, after it ``Lunar Month``.
LINE = re.compile(r"^(\d{4})/(\d{1,2})/(\d{1,2})\s+(\S+(?: Lunar Month)?)", re.IGNORECASE)
MONTH = re.compile(r"^(\d+)(?:st|nd|rd|th) Lunar Month$", re.IGNORECASE)

HEADER = '''# navml: generated by tools/chinese_calendar.py from the Hong Kong Observatory's
# Gregorian-Lunar Calendar Conversion Tables; do not edit.
"""The Chinese calendar's lunar years 1901 to 2099.

``YEARS[n]`` is lunar year ``FIRST_YEAR + n``: the ordinal of its first day
(``datetime.date.toordinal()``), its leap month's number (0 if none), and its
months' lengths in year order as bits, the first month the lowest, a set bit
30 days and a clear one 29.
"""

FIRST_YEAR = {first}

YEARS: tuple[tuple[int, int, int], ...] = (
'''


def fetch(year: int, cache: Path | None) -> str:
    if cache is not None:
        path = cache / f"T{year}e.txt"
        if path.exists():
            return path.read_text(encoding="utf-8-sig", errors="replace")
    with urllib.request.urlopen(URL.format(year=year), timeout=60) as response:
        # The older files' headings have a dash in another encoding; the
        # lines of days are ASCII.
        text = response.read().decode("utf-8-sig", errors="replace")
    if cache is not None:
        cache.mkdir(parents=True, exist_ok=True)
        (cache / f"T{year}e.txt").write_text(text, encoding="utf-8")
    return text


def month_starts(texts: list[str]) -> tuple[list[tuple[int, int]], int]:
    """Every lunar month's first day as ``(ordinal, number)``, and the day
    after the last one the files list."""
    starts: list[tuple[int, int]] = []
    last = number = 0
    for text in texts:
        for line in text.splitlines():
            match = LINE.match(line.strip())
            if not match:
                continue
            day = datetime.date(int(match[1]), int(match[2]), int(match[3])).toordinal()
            month = MONTH.match(match[4])
            if last and day != last + 1:
                # A day left out (2069's has no 30 December): harmless when
                # no month began in it, which the lunar days counting on say.
                if month or not match[4].isdigit() or int(match[4]) != number + day - last:
                    raise ValueError(f"the files skip from {datetime.date.fromordinal(last)} to {match[0]}")
                print(f"note: no line for {datetime.date.fromordinal(last + 1)}; the lunar days count on",
                      file=sys.stderr)
            last = day
            if month:
                starts.append((day, int(month[1])))
                number = 1
            elif match[4].isdigit():
                number = int(match[4])
    return starts, last + 1


def years(starts: list[tuple[int, int]], end: int) -> list[tuple[int, int, int, int]]:
    """``(year, first day, leap month, length bits)`` for each lunar year the
    months cover whole."""
    bounds = [day for day, _ in starts[1:]] + [end]
    found = []
    current = None
    previous = 0
    for (day, number), after in zip(starts, bounds):
        leap = number == previous
        previous = number
        if number == 1 and not leap:
            if current is not None:
                found.append(current)
            current = [datetime.date.fromordinal(day).year, day, 0, []]
        if current is None:
            continue  # a year begun before the first file
        if leap:
            current[2] = number
        current[3].append(after - day)
    # The last year runs on past the files.
    return [(year, first, leap, sum(1 << i for i, length in enumerate(lengths) if length == 30))
            for year, first, leap, lengths in found]


def module_text(table: list[tuple[int, int, int, int]]) -> str:
    rows = "".join(f"    ({first}, {leap}, 0x{bits:04x}),  # {year}\n" for year, first, leap, bits in table)
    return HEADER.format(first=table[0][0]) + rows + ")\n"


def check() -> int:
    namespace: dict = {}
    exec(MODULE.read_text(encoding="utf-8"), namespace)
    first, table = namespace["FIRST_YEAR"], namespace["YEARS"]
    problems = []
    for index, (start, leap, bits) in enumerate(table):
        months = 13 if leap else 12
        if bits >> months:
            problems.append(f"{first + index}: more months than {months}")
        if not 0 <= leap <= 12:
            problems.append(f"{first + index}: leap month {leap}")
        length = sum(30 if bits >> i & 1 else 29 for i in range(months))
        if index + 1 < len(table) and table[index + 1][0] - start != length:
            problems.append(f"{first + index}: its months are {length} days, the year {table[index + 1][0] - start}")
        if datetime.date.fromordinal(start).year != first + index:
            problems.append(f"{first + index}: begins in {datetime.date.fromordinal(start).year}")
    for problem in problems:
        print(f"{MODULE}: {problem}", file=sys.stderr)
    return 1 if problems else 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when the module is inconsistent")
    parser.add_argument("--cache", type=Path, help="keep the downloaded files here, and read them from here")
    args = parser.parse_args()
    if args.check:
        return check()
    texts = [fetch(year, args.cache) for year in range(FIRST_FILE, LAST_FILE + 1)]
    table = years(*month_starts(texts))
    MODULE.write_text(module_text(table), encoding="utf-8")
    print(f"wrote {MODULE}: lunar years {table[0][0]} to {table[-1][0]}")
    return check()


if __name__ == "__main__":
    sys.exit(main())
